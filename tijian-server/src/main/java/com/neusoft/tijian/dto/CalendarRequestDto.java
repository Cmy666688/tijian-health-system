package com.neusoft.tijian.dto;

public class CalendarRequestDto {
    private Integer hpId;
    private Integer year;
    private Integer month;
    public Integer getHpId() { return hpId; }
    public void setHpId(Integer value) { this.hpId = value; }
    public Integer getYear() { return year; }
    public void setYear(Integer value) { this.year = value; }
    public Integer getMonth() { return month; }
    public void setMonth(Integer value) { this.month = value; }
}
