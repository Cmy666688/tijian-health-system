package com.neusoft.tijian.po;

public class Hospital {
    private Integer hpId;
    private String name;
    private String picture;
    private String telephone;
    private String address;
    private String businessHours;
    private String deadline;
    private String rule;
    private Integer state;
    public Integer getHpId() { return hpId; }
    public void setHpId(Integer value) { this.hpId = value; }
    public String getName() { return name; }
    public void setName(String value) { this.name = value; }
    public String getPicture() { return picture; }
    public void setPicture(String value) { this.picture = value; }
    public String getTelephone() { return telephone; }
    public void setTelephone(String value) { this.telephone = value; }
    public String getAddress() { return address; }
    public void setAddress(String value) { this.address = value; }
    public String getBusinessHours() { return businessHours; }
    public void setBusinessHours(String value) { this.businessHours = value; }
    public String getDeadline() { return deadline; }
    public void setDeadline(String value) { this.deadline = value; }
    public String getRule() { return rule; }
    public void setRule(String value) { this.rule = value; }
    public Integer getState() { return state; }
    public void setState(Integer value) { this.state = value; }
}
