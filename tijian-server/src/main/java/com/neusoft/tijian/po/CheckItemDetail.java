package com.neusoft.tijian.po;

public class CheckItemDetail {
    private Integer cdId;
    private String name;
    private String unit;
    private String normalValueString;
    public Integer getCdId() { return cdId; }
    public void setCdId(Integer value) { this.cdId = value; }
    public String getName() { return name; }
    public void setName(String value) { this.name = value; }
    public String getUnit() { return unit; }
    public void setUnit(String value) { this.unit = value; }
    public String getNormalValueString() { return normalValueString; }
    public void setNormalValueString(String value) { this.normalValueString = value; }
}
